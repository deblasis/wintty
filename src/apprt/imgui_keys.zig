test "imguiKey numpad navigation" {
    const testing = std.testing;
    try testing.expect(imguiKey(input.Key.numpad_page_down).? == cimgui.c.ImGuiKey_PageDown);
    try testing.expect(imguiKey(input.Key.numpad_page_up).? == cimgui.c.ImGuiKey_PageUp);
    // ImGui has no Begin key; its enum range marker aliases Tab.
    try testing.expectEqual(@as(?c_int, null), imguiKey(input.Key.numpad_begin));
}
